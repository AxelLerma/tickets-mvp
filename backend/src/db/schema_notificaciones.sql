CREATE TABLE IF NOT EXISTS notificaciones (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  usuario_id INTEGER NOT NULL REFERENCES usuarios(id),
  ticket_id INTEGER REFERENCES tickets(id),
  tipo TEXT NOT NULL,
  titulo TEXT NOT NULL,
  mensaje TEXT NOT NULL,
  creada_en TIMESTAMPTZ NOT NULL,
  leida_en TIMESTAMPTZ,
  correo_estado TEXT NOT NULL DEFAULT 'pendiente' CHECK (correo_estado IN ('pendiente', 'enviado', 'error', 'omitido')),
  correo_intentos INTEGER NOT NULL DEFAULT 0,
  correo_error TEXT
);

CREATE INDEX IF NOT EXISTS idx_notificaciones_usuario ON notificaciones(usuario_id, leida_en);
CREATE INDEX IF NOT EXISTS idx_notificaciones_correo ON notificaciones(correo_estado) WHERE correo_estado = 'pendiente';