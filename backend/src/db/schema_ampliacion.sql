CREATE TABLE IF NOT EXISTS ticket_relaciones (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ticket_id INTEGER NOT NULL REFERENCES tickets(id),
  relacionado_id INTEGER NOT NULL REFERENCES tickets(id),
  creada_por INTEGER REFERENCES usuarios(id),
  creada_en TIMESTAMPTZ NOT NULL,
  activa BOOLEAN NOT NULL DEFAULT TRUE,
  CHECK (ticket_id < relacionado_id),
  UNIQUE (ticket_id, relacionado_id)
);

CREATE INDEX IF NOT EXISTS idx_relaciones_ticket ON ticket_relaciones(ticket_id);
CREATE INDEX IF NOT EXISTS idx_relaciones_relacionado ON ticket_relaciones(relacionado_id);